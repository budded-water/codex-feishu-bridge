import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';

const executable = process.env.CODEX_EXECUTABLE || 'codex';
const version = spawnSync(executable, ['--version'], { encoding: 'utf8' });
if (version.status !== 0) throw new Error('Cannot read Codex version');
const release = version.stdout.trim().match(/^codex-cli ([\w.-]+)$/)?.[1];
if (!release) throw new Error('Unexpected Codex version format');
const temporary = mkdtempSync(join(tmpdir(), 'codex-bridge-protocol-'));
const destination = resolve('src/codex/generated');
const seeds = [
  'InitializeParams', 'v2/ThreadStartParams', 'v2/ThreadResumeParams',
  'v2/TurnStartParams', 'v2/TurnSteerParams', 'v2/TurnInterruptParams',
  'v2/CommandExecutionRequestApprovalResponse', 'v2/FileChangeRequestApprovalResponse',
  'v2/ToolRequestUserInputParams', 'v2/ToolRequestUserInputResponse',
  'v2/PermissionsRequestApprovalResponse',
];
try {
  const generated = spawnSync(executable, ['app-server', 'generate-ts', '--out', temporary], { encoding: 'utf8' });
  if (generated.status !== 0) throw new Error('Cannot generate app-server bindings');
  rmSync(destination, { recursive: true, force: true });
  const copied = new Set();
  const copy = (name) => {
    const normalized = resolve(temporary, `${name}.ts`);
    if (copied.has(normalized)) return;
    copied.add(normalized);
    const original = readFileSync(normalized, 'utf8');
    const relative = normalized.slice(temporary.length + 1);
    const rewritten = original.replace(/from "(\.[^"]+)"/g, (_, dependency) => {
      copy(resolve(dirname(normalized), dependency).slice(temporary.length + 1));
      return `from "${dependency}.js"`;
    });
    const target = join(destination, relative);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, rewritten);
  };
  seeds.forEach(copy);
  writeFileSync(join(destination, 'version.ts'), `// Generated by scripts/generate-protocol.mjs.\nexport const CODEX_VERSION = '${release}';\n`);
  console.log(`Generated ${copied.size} protocol types from Codex ${release}; added .js import suffixes for Node ESM.`);
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
